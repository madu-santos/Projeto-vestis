-- Tabela de estabelecimentos (tenants/lojas) da plataforma Vestis.
CREATE TABLE stores (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    slug          VARCHAR(100) NOT NULL,
    logo_path     VARCHAR(255),
    contact_email VARCHAR(255),
    contact_phone VARCHAR(50),
    address       VARCHAR(255),
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_stores_slug UNIQUE (slug)
);

-- Caso existam contas antigas sem loja cadastrada no banco, cria uma loja de migração para backfill seguro.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM staff_accounts) AND NOT EXISTS (SELECT 1 FROM stores) THEN
        INSERT INTO stores (name, slug, enabled, created_at)
        VALUES ('Loja Padrao Migrada', 'loja-padrao-migrada', TRUE, now());
    END IF;
END $$;

-- Adiciona a coluna store_id em staff_accounts.
ALTER TABLE staff_accounts ADD COLUMN store_id BIGINT;

-- Backfill para associar contas existentes à loja criada acima, se houver registros.
UPDATE staff_accounts
SET store_id = (SELECT id FROM stores ORDER BY id LIMIT 1)
WHERE store_id IS NULL AND EXISTS (SELECT 1 FROM stores);

-- Torna store_id obrigatório e adiciona chave estrangeira e índice de consulta.
ALTER TABLE staff_accounts ALTER COLUMN store_id SET NOT NULL;
ALTER TABLE staff_accounts ADD CONSTRAINT fk_staff_accounts_store FOREIGN KEY (store_id) REFERENCES stores (id);
CREATE INDEX idx_staff_accounts_store_id ON staff_accounts (store_id);
